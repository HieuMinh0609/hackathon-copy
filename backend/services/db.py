_engines: dict[str, Engine] = {}
_lock = threading.Lock()


def get_engine(url: str) -> Engine:
    """Khởi tạo hoặc lấy SQLAlchemy Engine kết nối tới PostgreSQL (hoặc SQLite khi test) với connection pooling."""
    with _lock:
        engine = _engines.get(url)
        if engine is None:
            if url.startswith("sqlite"):
                from sqlalchemy.pool import NullPool
                engine = create_engine(url, poolclass=NullPool)
            else:
                engine = create_engine(
                    url,
                    pool_pre_ping=True,
                    pool_size=10,
                    max_overflow=20,
                    connect_args={"connect_timeout": 5},
                )
            _engines[url] = engine
        return engine


@contextmanager
def get_connection(url: str) -> Iterator[Connection]:
    """Mở transaction với PostgreSQL; tự commit khi thoát bình thường, rollback khi có lỗi."""
    with get_engine(url).begin() as conn:
        yield conn


def init_schema(url: str) -> None:
    """Khởi tạo schema toàn bộ bảng và chỉ mục trong cơ sở dữ liệu PostgreSQL."""
    with get_connection(url) as conn:
        for stmt in TABLE_STATEMENTS:
            conn.execute(text(stmt))
        # Migration cho user_checklists: đồng bộ role_id từ users hoặc role_in_project
        try:
            conn.execute(text("""
                UPDATE user_checklists
                SET role_id = (SELECT u.role_id FROM users u WHERE u.user_id = user_checklists.user_id)
                WHERE role_id IS NULL
            """))
        except Exception:
            pass


def describe(url: str) -> str:
    """Mô tả URL PostgreSQL đã che mật khẩu, dùng để hiển thị an toàn trên UI/log."""
    return make_url(url).render_as_string(hide_password=True)


def check_connection(url: str) -> tuple[bool, str]:
    """Kiểm tra kết nối thực tế tới PostgreSQL Server. Trả về (ok, thông báo)."""
    try:
        with get_engine(url).connect() as conn:
            version = conn.execute(text("SELECT version()")).scalar()
        return True, f"Kết nối PostgreSQL OK - {describe(url)} ({str(version)[:40]})"
    except Exception as exc:
        reason = str(getattr(exc, "orig", exc)).strip().splitlines()[0][:200]
        return False, f"Không kết nối được PostgreSQL {describe(url)}: {reason}"
