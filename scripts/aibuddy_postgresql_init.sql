-- Validate that an assigned task really belongs to the assigned template.
-- Also maintain completed_at and updated_at consistently.
CREATE OR REPLACE FUNCTION aibuddy_prepare_user_task()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM user_checklists c
        JOIN onboarding_template_tasks t ON t.template_id = c.template_id
        WHERE c.checklist_id = NEW.checklist_id
          AND t.template_task_id = NEW.template_task_id
    ) THEN
        RAISE EXCEPTION
            'template_task_id % does not belong to checklist_id %',
            NEW.template_task_id, NEW.checklist_id;
    END IF;

    IF NEW.status = 'COMPLETED' THEN
        NEW.completed_at := COALESCE(NEW.completed_at, NOW());
    ELSE
        NEW.completed_at := NULL;
    END IF;
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_prepare_user_task ON user_checklists_tasks;
CREATE TRIGGER trg_prepare_user_task
BEFORE INSERT OR UPDATE ON user_checklists_tasks
FOR EACH ROW EXECUTE FUNCTION aibuddy_prepare_user_task();

-- Recalculate progress and status on each task change. The parent row is
-- locked first to serialize concurrent updates to different tasks in one list.
-- BLOCKED has priority. Completion requires all tasks (including optional).
-- An empty checklist remains NOT_STARTED (0%).
CREATE OR REPLACE FUNCTION aibuddy_recalculate_checklist(p_checklist_id BIGINT)
RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE
    v_total        BIGINT;
    v_completed    BIGINT;
    v_blocked      BOOLEAN;
    v_started      BOOLEAN;
    v_progress     SMALLINT;
    v_status       VARCHAR(20);
BEGIN
    -- On cascading deletion the parent may no longer exist.
    PERFORM 1 FROM user_checklists
     WHERE checklist_id = p_checklist_id FOR UPDATE;
    IF NOT FOUND THEN
        RETURN;
    END IF;

    SELECT COUNT(*),
           COUNT(*) FILTER (WHERE status = 'COMPLETED'),
           COALESCE(BOOL_OR(status = 'BLOCKED'), FALSE),
           COALESCE(BOOL_OR(status IN ('IN_PROGRESS', 'COMPLETED')), FALSE)
      INTO v_total, v_completed, v_blocked, v_started
      FROM user_checklists_tasks
     WHERE checklist_id = p_checklist_id;

    v_progress := CASE WHEN v_total = 0 THEN 0
                  ELSE ROUND(100.0 * v_completed / v_total)::SMALLINT END;
    v_status := CASE
        WHEN v_blocked THEN 'BLOCKED'
        WHEN v_total > 0 AND v_completed = v_total THEN 'COMPLETED'
        WHEN v_started THEN 'IN_PROGRESS'
        ELSE 'NOT_STARTED'
    END;

    UPDATE user_checklists
       SET progress = v_progress, status = v_status
     WHERE checklist_id = p_checklist_id
       AND (progress IS DISTINCT FROM v_progress
            OR status IS DISTINCT FROM v_status);
END;
$$;

CREATE OR REPLACE FUNCTION aibuddy_refresh_checklist_progress()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        PERFORM aibuddy_recalculate_checklist(OLD.checklist_id);
    ELSE
        PERFORM aibuddy_recalculate_checklist(NEW.checklist_id);
        IF TG_OP = 'UPDATE' AND OLD.checklist_id <> NEW.checklist_id THEN
            PERFORM aibuddy_recalculate_checklist(OLD.checklist_id);
        END IF;
    END IF;
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_refresh_checklist_progress ON user_checklists_tasks;
CREATE TRIGGER trg_refresh_checklist_progress
AFTER INSERT OR UPDATE OR DELETE ON user_checklists_tasks
FOR EACH ROW EXECUTE FUNCTION aibuddy_refresh_checklist_progress();

-- Assigning a checklist automatically copies all tasks from that template.
CREATE OR REPLACE FUNCTION aibuddy_create_checklist_tasks()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO user_checklists_tasks (checklist_id, template_task_id)
    SELECT NEW.checklist_id, t.template_task_id
     FROM onboarding_template_tasks t
     WHERE t.template_id = NEW.template_id
     ORDER BY t.sort_order, t.template_task_id
    ON CONFLICT (checklist_id, template_task_id) DO NOTHING;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_create_checklist_tasks ON user_checklists;
CREATE TRIGGER trg_create_checklist_tasks
AFTER INSERT ON user_checklists
FOR EACH ROW EXECUTE FUNCTION aibuddy_create_checklist_tasks();

